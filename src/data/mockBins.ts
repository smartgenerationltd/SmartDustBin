const generateHistoricalReadings = (
  currentFood: number,
  currentRecycling: number,
  currentGeneral: number,
  currentTemp: number,
  currentBattery: number
): SensorReading[] => {
  const readings: SensorReading[] = [];
  const now = Date.now();
  for (let i = 24; i >= 0; i--) {
    const time = new Date(now - i * 3600 * 1000).toISOString();
    // generate gentle climb towards current
    const progress = (24 - i) / 24;
    const food = Math.max(10, Math.min(100, Math.round(currentFood * 0.4 + currentFood * 0.6 * progress + (Math.random() * 6 - 3))));
    const rec = Math.max(10, Math.min(100, Math.round(currentRecycling * 0.35 + currentRecycling * 0.65 * progress + (Math.random() * 6 - 3))));
    const gen = Math.max(10, Math.min(100, Math.round(currentGeneral * 0.5 + currentGeneral * 0.5 * progress + (Math.random() * 6 - 3))));
    const temp = Math.round(currentTemp + Math.sin((24 - i) / 4) * 4);
    const bat = Math.max(20, Math.min(100, Math.round(currentBattery + (i > 12 ? (12 - i) * 0.8 : (12 - i) * 0.4))));

    readings.push({
      timestamp: time,
      foodFillLevel: i === 0 ? currentFood : food,
      recyclingFillLevel: i === 0 ? currentRecycling : rec,
      generalFillLevel: i === 0 ? currentGeneral : gen,
      temperature: i === 0 ? currentTemp : temp,
      humidity: Math.round(55 + Math.cos(i) * 12),
      batteryLevel: i === 0 ? currentBattery : bat,
      solarVoltage: 18.4,
    });
  }
  return readings;
};

